// Keeps the documentation tabs in step with docs/.
//
// The tabs are the data-doc attributes in index.html. For each one, this copies docs/<name>.md to
// website/docs/<name>.md and writes docs-content.js, which embeds the same text. The embedded copy
// lets the page work when index.html is opened straight from disk, where fetch() is blocked.
//
// Usage: node website/sync-docs.mjs
import {copyFile, mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const website = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(website, '..');
const html = await readFile(path.join(website, 'index.html'), 'utf8');
const tabs = [...html.matchAll(/data-doc="(docs\/[^"]+\.md)"/g)].map(match => match[1]);
if (!tabs.length) throw new Error('No data-doc tabs found in index.html');

await mkdir(path.join(website, 'docs'), {recursive: true});
const embedded = {};
for (const doc of new Set(tabs)) {
  const name = path.basename(doc);
  const source = path.join(repo, 'docs', name);
  await copyFile(source, path.join(website, 'docs', name));
  embedded[doc] = await readFile(source, 'utf8');
}

const script = `// Generated by website/sync-docs.mjs from docs/. Do not edit by hand.\n` +
  `window.RENDRIX_DOCS = ${JSON.stringify(embedded, null, 2)};\n`;
await writeFile(path.join(website, 'docs-content.js'), script);
console.log(`Synced ${tabs.length} documents: ${tabs.join(', ')}`);
